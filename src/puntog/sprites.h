// Fast 2-bit indexed sprite renderer with origin translation and screen clipping
static inline void draw_sprite_2bpp(int world_x, int world_y, const uint8_t *data,
				    int w, int h, Palette4 pal, bool flip_x)
{
	int bytes_per_row = (w + 3) / 4;

	for (int dy = 0; dy < h; dy++) {
		int py = world_y + dy;

		for (int dx = 0; dx < w; dx++) {
			int px = flip_x ? (world_x + (w - 1 - dx)) : (world_x + dx);

			int byte_idx = dy * bytes_per_row + (dx / 4);
			int bit_shift = 6 - (dx % 4) * 2;
			uint8_t color_idx = (data[byte_idx] >> bit_shift) & 0x03;

			if (color_idx > 0) {
				tft_draw_pixel(px, py, pal.c[color_idx]);
			}
		}
	}
}

