static inline void hud_draw_text(int sx, int sy, color_t color, const char *str)
{
	while (*str) {
		unsigned char c = (unsigned char)*str++;
		if (c >= 128) c = ' ';
		uint16_t glyph = font3x5[c];
		for (int row = 0; row < 5; row++) {
			int py = sy + row;
			if (py < 0 || py >= TFT_HEIGHT) continue;
			for (int col = 0; col < 3; col++) {
				int px = sx + col;
				if (px < 0 || px >= TFT_WIDTH) continue;
				int bit = 14 - (row * 3 + col);
				if ((glyph >> bit) & 1) {
					tft_draw_pixel(px, py, color);
				}
			}
		}
		sx += 4;
	}
}

static inline void hud_draw_text_fmt(int sx, int sy, color_t color, const char *fmt, ...)
{
	char buf[48];
	va_list args;
	va_start(args, fmt);
	vsnprintf(buf, sizeof(buf), fmt, args);
	va_end(args);
	hud_draw_text(sx, sy, color, buf);
}
